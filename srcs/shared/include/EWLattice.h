#pragma once  /* -*- C++ -*- */
/* EWLattice.h -- perfect tilings of the plane by Manhattan diamonds
   ('tiles') and the 'rect-snap' hub geometry built on them.  Branch
   diagonal-tiles; design and measurements in GEOMETRY.md sec 10
   (scripts/geomlab).

   THE LATTICE.  Radius-T Manhattan diamonds (2T^2 + 2T + 1 sites) tile
   the plane exactly when their centers are the lattice generated by
   (T, T+1) and (-(T+1), T): a site (x, y), in GLOBAL site coordinates,
   is a center iff (T x + (T+1) y - C0) mod SITES == 0.  The SITES
   offsets of a tile have SITES different values of (T dx + (T+1) dy)
   mod SITES, so a site's residue names its offset from its own tile's
   center: no per-site table.  The residue order 0..SITES-1 is also the
   canonical order of a tile's sites.  T = 4 (41 sites) makes every tile
   exactly one event window (EW); policy ewsnap uses that.  A bigger T
   (policy ewsnap10: T = 10, 221 sites) gives hub boundaries with longer
   straight 45-degree runs; events still use radius-4 windows
   (WINDOW_RADIUS) inside the snapped areas.  The tile radius is a
   template parameter (EWLatticeT<T>); EWLattice = EWLatticeT<4>.

   RECT-SNAP.  Hubs keep today's SELF rectangles (BW x BH, DemoGlobal.h),
   but every tile belongs WHOLE to the hub whose rectangle holds its
   center.  A cache condition (Corner4, the NEW_LEADER argument under
   four corners) shifts every hub's event area by SHIFT toward that
   corner: the area is every tile whose center lies in the hub's
   rectangle moved by cornerShift(c).  So every owned, borrowed and lent
   set is the set of tiles whose centers lie in a RECTANGLE (an
   intersection of rectangles), and a band is enumerated by walking those
   centers in row-major order and emitting each tile's sites in residue
   order.  Both ends of a band compute the same global rectangle, so they
   walk the same sites in the same order.  A side of a hub with no
   neighbor (a permanent edge) extends its rectangle EDGE_REACH past the
   grid: a tile with any site on the grid has its center at most T off,
   and the event area moved SHIFT away from that edge must still reach
   it.  Its off-grid sites are INACCESSIBLE and skipped (onGrid) by both
   ends alike; a walk may also meet a few centers whose tiles miss the
   grid entirely (all sites skipped).  Event centers: a site is a live
   center in a condition iff its whole radius-4 window lies in the area
   (or is inaccessible); buildCenterTable lists them.

   Coordinates are GLOBAL sites (0..ACTIVE_GRID_WIDTH-1 etc.); a hub
   converts to its own grid by subtracting its origin.  Pure arithmetic,
   host-testable: srcs/host/tools/ewlattice_test.cpp (every supported T).
*/
