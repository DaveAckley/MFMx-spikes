// ethlinktest12.cpp -- measures, WITH AN E1 DIAGNOSTIC IMAGE, the order in which an Ethernet RX queue commits an
// incoming TT-link L1-write packet to the receiving tile's L1.  Answers: can MFMx's header/ankle/footer nonce
// completeness rule (TCBase::isComplete) be reused unchanged on the ETH hop?
//
// WHY E1: a host over PCIe cannot see this (a PCIe read takes ~0.85 us, a packet lands in tens of ns).  A
// RISC-V core reading its own L1 back-to-back can.  The E1 image (e1order/e1order.c, embedded below) reads a
// slot's footer, ankle, mid-payload word, then header, in that order, ~2 ns apart, and classifies each as
// same/newer/older than the footer's version.  "older" => the footer overtook that word.
//
// FLOW (one link, tx = A -> rx = B, E1 runs on B only):
//   configure queue 2 on both ends (as ethlinktest11) -> smoke -> deploy E1 on B (official ethdump sequence:
//   write code to L1, set E1 reset/end PC, release E1 from soft reset) -> baseline with no traffic (expect all
//   "same") -> for each packet size, A streams N MFMx-format packets (versions cycling 0..K-1) into one fixed
//   slot on B while the E1 samples -> print results -> put E1 back in reset, restore PCs and queue 2.
//
// SAFETY: default is a DRY RUN (reads only).  --go enables writes.  Writes are allowlisted (write_ok): queue 2,
// TX header entry 1, L1 scratch 0x10000..0x6FFFF, E1 code at 0x4000, E1 control block 0x8000, E1 PC regs, and
// the soft-reset register restricted to {original value, original with only the E1 bit cleared}.  E1's image only
// READS one L1 slot and writes its results block.  The tt-kmd NOC_CLEANUP ioctl is armed so E1 returns to reset
// even if this process dies (needs recent tt-kmd; failure is reported, not fatal).  Refuses if E1 is not in reset.
//
// LIMITS: "older" counts are one-sided evidence; zero older over millions of packets at each size is strong but
// not proof.  E1 samples L1 through its own load path (L1 port arbitration between E1 loads and RX-queue stores
// is itself a hardware detail), so treat results as "what a core on this tile sees", which is what an E1
// forwarder would see.  The T6-over-NoC-read case is different and is NOT covered here.
//
// Build: g++ -std=c++17 -O2 -Wall -Wextra -Werror ethlinktest12.cpp -o ethlinktest12
// Run:   ./ethlinktest12 --link 0:1:6                  # dry run
//        ./ethlinktest12 --link 0:1:6 --go             # does the test (receiver = card 1)
//
// ioctl plumbing copied from ethprobe12.cpp / ethdump.c (Tenstorrent, Apache-2.0: SET_NOC_CLEANUP usage).
// The embedded E1 image is generated by e1order/build.sh from e1order/e1order.c.
