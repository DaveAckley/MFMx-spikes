#!/usr/bin/env python3
"""benchgen.py -- the BytePhys per-opcode microbenchmark programs.

Writes scripts/bytephys/bench/*.bp (GENERATED; bpasm.py assembles them
into srcs/shared/include/ByteBench.h, namespace BytePhys::Bench).  The
EWP runs them when an event lands on a Bench atom (type 31, `seed 3
31`): ewp/src/Physics.cpp runBench, `.pb` marks, runsum.py's
'bytecode microbenchmark' section.  BYTEPHYS.md section 10.

Every program has the same frame: open a 4-slot frame, push two
dummies (so over/swap have operands), then loop PASSES times over a
body of COPIES copies of one PATTERN, with the loop counter on the
operand stack:

        enter 0 4
        push 5
        push 6
        push PASSES
  loop: PATTERN x COPIES
        push 1 / sub / dup / jnz loop
        drop / drop / drop / halt1

`base` has an empty body, so (cycles - base cycles) / (insns - base
insns) is the mean cost of one instruction of the pattern.  Every
pattern leaves the operand stack as it found it.  `{n}` in a pattern
is a label unique to that copy.

Usage:
  benchgen.py            regenerate bench/*.bp
  benchgen.py --check    exit 1 if any is out of date
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUTDIR = os.path.join(HERE, "bench")

PASSES = 50
COPIES = 8
BENCH_TYPE = 31                 # ewp/src/Physics.cpp PHY_BENCH

# name (at most 7 chars: it rides in the .pb mark) -> pattern
PATTERNS = [
    ("base", []),
    ("jmp", ["jmp {n}", "{n}:"]),
    ("push8", ["push 7", "drop"]),
    ("push32", ["push 100000", "drop"]),
    ("dup", ["dup", "drop"]),
    ("over", ["over", "drop"]),
    ("swap", ["swap", "swap"]),
    ("add", ["push 0", "add"]),
    ("sub", ["push 0", "sub"]),
    ("eq", ["dup", "dup", "eq", "drop"]),
    ("lt", ["dup", "dup", "lt", "drop"]),
    ("jz", ["push 1", "jz loop"]),              # never taken
    ("jnz", ["push 1", "jnz {n}", "{n}:"]),     # always taken
    ("call", ["call f_ret"]),                   # call + ret
    ("enter", ["call f_enter"]),                # call + enter + ret
    ("loadl", ["loadl 0", "drop"]),
    ("storel", ["dup", "storel 1"]),
    ("getf", ["push 0", "getf stg0", "drop"]),
    ("setf", ["push 0", "push 3", "setf stg1"]),
    ("getm1", ["push 0", "getm Bench.c", "drop"]),      # one word
    ("getm2", ["push 0", "getm Bench.b", "drop"]),      # straddles
    ("setm1", ["push 0", "push 9", "setm Bench.c"]),
    ("setm2", ["push 0", "push 9", "setm Bench.b"]),
    ("copy", ["push 0", "push 0", "copy"]),             # site 0 to 0
    ("between", ["push 1", "push 10", "between", "drop"]),
    ("onein", ["push 2", "onein", "drop"]),
]

GEN = "; GENERATED by scripts/bytephys/benchgen.py: edit that, not this."


def decl_text():
    # members: a fast-path member (c, inside mStg[1]) and one that
    # straddles mStg[0]/mStg[1] (b); idx is mData0, runBench's counter
    return "\n".join([
        GEN,
        "",
        f"element Bench {BENCH_TYPE}",
        "  unsigned a 8          ; bits 0..7",
        "  unsigned b 32         ; bits 8..39 (straddles two words)",
        "  unsigned c 16         ; bits 40..55 (one word)",
        "  unsigned pad 8        ; bits 56..63",
        "  unsigned idx 16       ; bits 64..79 = mData0 (runBench's)",
        ""])


def prog_text(name, pattern):
    lines = [GEN,
             f"; bench {name}: {COPIES} copies of the pattern per pass, "
             f"{PASSES} passes",
             "",
             "        enter 0 4",
             "        push 5",
             "        push 6",
             f"        push {PASSES}",
             "loop:"]
    for k in range(COPIES):
        for p in pattern:
            s = p.format(n=f"n{k}")
            lines.append(s if s.endswith(":") else "        " + s)
    lines += ["        push 1",
              "        sub",
              "        dup",
              "        jnz loop",
              "        drop",
              "        drop",
              "        drop",
              "        halt1",
              "f_ret:",
              "        ret",
              "f_enter:",
              "        enter 0 2",
              "        ret",
              ""]
    return "\n".join(lines)


def texts():
    out = {"bench.bp": decl_text()}
    for i, (name, pat) in enumerate(PATTERNS):
        assert len(name) <= 7, name
        # zero-padded index first, so bpasm's sorted order is this order
        out[f"b{i:02d}_{name}.bp"] = prog_text(name, pat)
    return out


def main(argv):
    want = texts()
    if argv[:1] == ["--check"]:
        bad = []
        for f, t in want.items():
            p = os.path.join(OUTDIR, f)
            if not os.path.exists(p) or open(p).read() != t:
                bad.append(f)
        have = {f for f in os.listdir(OUTDIR) if f.endswith(".bp")} \
            if os.path.isdir(OUTDIR) else set()
        bad += sorted(have - set(want))
        if bad:
            print(f"benchgen --check: OUT OF DATE: {', '.join(bad)} "
                  "(run scripts/bytephys/benchgen.py)")
            return 1
        print(f"benchgen --check: {len(want)} files current")
        return 0
    os.makedirs(OUTDIR, exist_ok=True)
    for f in os.listdir(OUTDIR):
        if f.endswith(".bp") and f not in want:
            os.remove(os.path.join(OUTDIR, f))
    for f, t in want.items():
        open(os.path.join(OUTDIR, f), "w").write(t)
    print(f"benchgen: wrote {len(want)} files in "
          f"{os.path.relpath(OUTDIR, os.path.dirname(HERE))}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
