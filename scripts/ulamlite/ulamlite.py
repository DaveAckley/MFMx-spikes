#!/usr/bin/env python3
"""ulamlite.py -- compile ulam-lite (a small ulam-like language) to bpasm.

Reads scripts/ulamlite/*.ulam and writes one GENERATED .bp file per
quark and per element into scripts/bytephys (aging.bp, bfb1.bp, ...),
which bpasm.py then assembles into BytePrograms.h.  Manual: BYTEPHYS.md
section 13.

The language (milestone 1):

  quark Aging {                        // a bundle of members
    Unsigned(32) fuse;
    Unsigned(32) age;
  }
  element BFB1 {                       // an atom type
    constant Unsigned cOLD = 21;
    Aging a;                           // members: Unsigned(n) (1..32),
                                       //   Unsigned (= 32), Bool, a quark
    Void behave() { ... }              // the event: runs on ew[0]
    Void kabam() { ... }               // more methods: Void, Unsigned,
    Unsigned f(Unsigned x) { ... }     //   Bool; params and locals
  }

Statements: { ... }, local declarations (Unsigned x = 3; Unsigned(4) n;
Bool b;), assignment (= += -=) and x++ / x-- on locals, self's members
(a.age) and window sites (ew[e] = self / ew[e] / Empty), if / else,
while, for, break, continue, return, method calls.
Expressions: unsigned literals, constants, locals, self's members,
+ - (saturating), == != < <= > >=, && || ! (short-circuit), method
calls, random.between(lo, hi), random.oneIn(n), ew[e] is TYPE.

Semantics follow the machine (BytePhys.h): values are u32; + and -
saturate; storing into Unsigned(n) (member or local) clamps to n bits;
Bool stores are 0 or 1.  A member named bare (a.age) is self's, i.e.
ew[0]'s.  behave() returning ends the event and commits the window.
Evaluation order: ew[dst] = src evaluates src first (as C++17 does).

Type numbers: like culam, the compiler assigns them, so a whole physics
is compiled at once.  Elements are numbered from FIRST_TYPE (above the
native types 0..6 of ewp Physics.cpp) in order of name, so FB1's BFB1 is
7 and BFB4 is 8.  Adding an element can renumber the ones sorting after
it: seeding and timing by number (seed 3 8, .pt slots) follow the
generated BP_TYPE_<NAME> values.

Usage:
  ulamlite.py              regenerate the .bp files
  ulamlite.py --check      exit 1 if any generated .bp is out of date
  ulamlite.py --print F    print what F would generate
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
OUTDIR = os.path.join(ROOT, "scripts", "bytephys")
GEN_MARK = "; GENERATED by scripts/ulamlite/ulamlite.py"

SITES = 41
FIRST_TYPE = 7                  # ewp Physics.cpp: 0..6 are native types


class CompileError(Exception):
    pass


# ---------------------------------------------------------------- lexer

TOKEN = re.compile(r"""
    (?P<ws>\s+|//[^\n]*|/\*.*?\*/)
  | (?P<num>0[xX][0-9a-fA-F]+|\d+)
  | (?P<name>[A-Za-z_]\w*)
  | (?P<op>\+\+|--|\+=|-=|==|!=|<=|>=|&&|\|\||[-+<>=!(){}\[\];,.])
""", re.S | re.X)


class Tok:
    def __init__(self, kind, text, line):
        self.kind, self.text, self.line = kind, text, line

    def __repr__(self):
        return f"{self.text!r}@{self.line}"


def lex(src, path):
    out, pos, line = [], 0, 1
    while pos < len(src):
        m = TOKEN.match(src, pos)
        if not m:
            raise CompileError(f"{path}:{line}: bad character "
                               f"{src[pos]!r}")
        kind = m.lastgroup
        text = m.group(kind)
        if kind != "ws":
            out.append(Tok(kind, text, line))
        line += text.count("\n")
        pos = m.end()
    out.append(Tok("eof", "", line))
    return out


# --------------------------------------------------------------- parser
# The AST is tuples: (kind, line, ...).

class Parser:
    def __init__(self, toks, path):
        self.t, self.i, self.path = toks, 0, path

    def peek(self, k=0):
        return self.t[self.i + k]

    def err(self, msg, tok=None):
        tok = tok or self.peek()
        raise CompileError(f"{self.path}:{tok.line}: {msg} "
                           f"(at {tok.text!r})")

    def take(self, text=None, kind=None):
        tok = self.peek()
        if (text is not None and tok.text != text) or \
           (kind is not None and tok.kind != kind):
            self.err(f"expected {text or kind}")
        self.i += 1
        return tok

    def at(self, text):
        return self.peek().text == text

    def maybe(self, text):
        if self.at(text):
            self.i += 1
            return True
        return False

    # -- top level

    def unit(self):
        decls = []
        while self.peek().kind != "eof":
            if self.at("quark"):
                decls.append(self.quark())
            elif self.at("element"):
                decls.append(self.element())
            else:
                self.err("expected quark or element")
        return decls

    def quark(self):
        line = self.take("quark").line
        name = self.take(kind="name").text
        self.take("{")
        members = []
        while not self.maybe("}"):
            typ = self.type_()
            mname = self.take(kind="name").text
            self.take(";")
            members.append((mname, typ, line))
        return ("quark", line, name, members)

    def element(self):
        line = self.take("element").line
        name = self.take(kind="name").text
        if self.at("="):
            self.err("the compiler assigns type numbers (like culam): "
                     "drop the '= N'")
        num = None                      # assigned by Program
        self.take("{")
        members, methods, consts = [], [], {}
        while not self.maybe("}"):
            if self.maybe("constant"):
                self.type_()
                cname = self.take(kind="name").text
                self.take("=")
                consts[cname] = int(self.take(kind="num").text, 0)
                self.take(";")
                continue
            tline = self.peek().line
            typ = self.type_(void_ok=True)
            mname = self.take(kind="name").text
            if self.at("("):
                methods.append(self.method(typ, mname, tline))
            else:
                if typ == ("void",):
                    self.err("a member cannot be Void")
                self.take(";")
                members.append((mname, typ, tline))
        return ("element", line, name, num, members, methods, consts)

    def type_(self, void_ok=False):
        tok = self.take(kind="name")
        if tok.text == "Unsigned":
            bits = 32
            if self.maybe("("):
                bits = int(self.take(kind="num").text, 0)
                self.take(")")
            if not 1 <= bits <= 32:
                self.err("Unsigned(n) needs 1 <= n <= 32", tok)
            return ("u", bits)
        if tok.text == "Bool":
            return ("bool",)
        if tok.text == "Void":
            if not void_ok:
                self.err("Void only as a return type", tok)
            return ("void",)
        return ("quark", tok.text)

    def method(self, ret, name, line):
        self.take("(")
        params = []
        if not self.at(")"):
            while True:
                typ = self.type_()
                if typ[0] == "quark":
                    self.err("parameters are Unsigned(n) or Bool")
                params.append((self.take(kind="name").text, typ))
                if not self.maybe(","):
                    break
        self.take(")")
        return ("method", line, name, ret, params, self.block())

    # -- statements

    def block(self):
        line = self.take("{").line
        body = []
        while not self.maybe("}"):
            body.append(self.stmt())
        return ("block", line, body)

    def is_local_decl(self):
        tok = self.peek()
        return tok.text in ("Unsigned", "Bool") and \
            (self.peek(1).kind == "name" or self.peek(1).text == "(")

    def stmt(self):
        tok = self.peek()
        line = tok.line
        if tok.text == "{":
            return self.block()
        if tok.text == "if":
            self.i += 1
            self.take("(")
            cond = self.expr()
            self.take(")")
            then = self.stmt()
            other = self.stmt() if self.maybe("else") else None
            return ("if", line, cond, then, other)
        if tok.text == "while":
            self.i += 1
            self.take("(")
            cond = self.expr()
            self.take(")")
            return ("while", line, cond, self.stmt())
        if tok.text == "for":
            self.i += 1
            self.take("(")
            init = None if self.at(";") else self.simple()
            self.take(";")
            cond = None if self.at(";") else self.expr()
            self.take(";")
            step = None if self.at(")") else self.simple()
            self.take(")")
            return ("for", line, init, cond, step, self.stmt())
        if tok.text in ("break", "continue"):
            self.i += 1
            self.take(";")
            return (tok.text, line)
        if tok.text == "return":
            self.i += 1
            val = None if self.at(";") else self.expr()
            self.take(";")
            return ("return", line, val)
        s = self.simple()
        self.take(";")
        return s

    def simple(self):
        """A declaration, assignment, ++/--, or expression statement."""
        line = self.peek().line
        if self.is_local_decl():
            typ = self.type_()
            name = self.take(kind="name").text
            init = self.expr() if self.maybe("=") else None
            return ("local", line, name, typ, init)
        e = self.expr()
        for op in ("=", "+=", "-="):
            if self.maybe(op):
                return ("assign", line, op, e, self.expr())
        for op in ("++", "--"):
            if self.maybe(op):
                return ("assign", line, "+=" if op == "++" else "-=", e,
                        ("num", line, 1))
        return ("expr", line, e)

    # -- expressions, loosest first

    def expr(self):
        return self.binary(0)

    LEVELS = [("||",), ("&&",), ("==", "!="), ("<", "<=", ">", ">="),
              ("+", "-")]

    def binary(self, level):
        if level == len(self.LEVELS):
            return self.unary()
        left = self.binary(level + 1)
        while self.peek().text in self.LEVELS[level]:
            tok = self.take()
            right = self.binary(level + 1)
            left = ("bin", tok.line, tok.text, left, right)
        return left

    def unary(self):
        if self.at("!"):
            line = self.take().line
            return ("not", line, self.unary())
        return self.postfix()

    def postfix(self):
        e = self.primary()
        while True:
            if self.at("."):
                self.take()
                e = ("dot", e[1], e, self.take(kind="name").text)
            elif self.at("["):
                self.take()
                idx = self.expr()
                self.take("]")
                e = ("index", e[1], e, idx)
            elif self.at("("):
                self.take()
                args = []
                if not self.at(")"):
                    while True:
                        args.append(self.expr())
                        if not self.maybe(","):
                            break
                self.take(")")
                e = ("call", e[1], e, args)
            elif self.at("is"):
                self.take()
                e = ("is", e[1], e, self.take(kind="name").text)
            else:
                return e

    def primary(self):
        tok = self.take()
        if tok.kind == "num":
            v = int(tok.text, 0)
            if v >= 1 << 32:
                self.err("number too big for 32 bits", tok)
            return ("num", tok.line, v)
        if tok.kind == "name":
            if tok.text == "true":
                return ("num", tok.line, 1)
            if tok.text == "false":
                return ("num", tok.line, 0)
            return ("name", tok.line, tok.text)
        if tok.text == "(":
            e = self.expr()
            self.take(")")
            return e
        self.err("expected an expression", tok)


# ------------------------------------------------------------- checking

class Program:
    """Every quark and element of a compile, by name."""

    def __init__(self, units):
        self.quarks, self.elements = {}, {}
        for path, decls in units:
            for d in decls:
                table = self.quarks if d[0] == "quark" else self.elements
                if d[2] in self.quarks or d[2] in self.elements:
                    raise CompileError(f"{path}:{d[1]}: {d[2]} declared "
                                       f"twice")
                table[d[2]] = (path, d)
        for i, name in enumerate(sorted(self.elements)):
            path, d = self.elements[name]
            d = d[:3] + (FIRST_TYPE + i,) + d[4:]
            self.elements[name] = (path, d)
        if FIRST_TYPE + len(self.elements) > 1 << 15:
            raise CompileError("too many element types")
        for name, (path, d) in self.elements.items():
            for m, typ, line in d[4]:
                self.check_type(typ, path, line)
        for name, (path, d) in self.quarks.items():
            for m, typ, line in d[3]:
                self.check_type(typ, path, line)

    def check_type(self, typ, path, line):
        if typ[0] == "quark" and typ[1] not in self.quarks:
            raise CompileError(f"{path}:{line}: no quark {typ[1]}")

    def members_of(self, typ):
        """Member list of a quark type."""
        return self.quarks[typ[1]][1][3]


# --------------------------------------------------------------- codegen

def member_line(name, typ):
    if typ[0] == "u":
        return f"  unsigned {name} {typ[1]}"
    if typ[0] == "bool":
        return f"  bool {name}"
    return f"  {typ[1]} {name}"


class Gen:
    """Code for one element."""

    def __init__(self, prog, path, elem):
        self.prog, self.path = prog, path
        (_, self.line, self.name, self.num, self.members, methods,
         self.consts) = elem
        self.methods = {m[2]: m for m in methods}
        if len(self.methods) != len(methods):
            raise CompileError(f"{path}:{self.line}: two methods with one "
                               f"name in {self.name}")
        if "behave" not in self.methods:
            raise CompileError(f"{path}:{self.line}: {self.name} has no "
                               f"behave()")
        b = self.methods["behave"]
        if b[3] != ("void",) or b[4]:
            raise CompileError(f"{path}:{b[1]}: behave() must be "
                               f"Void behave()")
        self.out = []
        self.nlabel = 0

    def err(self, line, msg):
        raise CompileError(f"{self.path}:{line}: {msg}")

    def emit(self, s):
        self.out.append(f"        {s}")

    def label(self, lab):
        self.out.append(f"{lab}:")

    def new_label(self, what):
        self.nlabel += 1
        return f"L{self.nlabel}_{what}"

    # -- methods

    def compile(self):
        lines = [f"element {self.name} {self.num}"]
        lines += [member_line(m, t) for m, t, _ in self.members]
        order = ["behave"] + [n for n in self.methods if n != "behave"]
        for name in order:
            self.method(self.methods[name])
        return lines + [""] + self.out

    def method(self, m):
        _, line, name, ret, params, body = m
        self.ret = ret
        self.is_behave = name == "behave"
        self.locals = {}            # name -> (slot, type); flat per method
        self.scopes = [set()]
        self.loops = []
        for p, typ in params:
            self.declare(p, typ, line)
        self.out.append(f"; {'Void' if ret == ('void',) else 'value'} "
                        f"{name}() -- {self.path}:{line}")
        enter_at = len(self.out)
        self.label(f"m_{name}")
        self.out.append(None)       # the enter, once the locals are known
        self.stmt(body)
        if self.is_behave:
            self.emit("halt1             ; end of behave: commit")
        elif ret == ("void",):
            self.emit("ret")
        else:
            self.emit("push 0            ; fell off the end: 0")
            self.emit("ret")
        n = len(self.locals)
        if n > 255:
            self.err(line, "too many locals")
        if n:
            names = [k.lstrip("~").split("#")[0] for k in self.locals]
            self.out[enter_at + 1] = (f"        enter {len(params)} {n}"
                                      f"         ; {', '.join(names)}")
        else:
            del self.out[enter_at + 1]

    def declare(self, name, typ, line):
        if name in self.scopes[-1]:
            self.err(line, f"{name} declared twice")
        if name in self.consts or self.member(name) is not None:
            self.err(line, f"local {name} hides a member or constant")
        slot = len(self.locals)
        key = name if name not in self.locals else f"{name}#{slot}"
        self.locals[key] = (slot, typ)
        self.scopes[-1].add(name)
        return slot

    def find_local(self, name):
        # the most recent declaration of name still in scope
        for key in reversed(list(self.locals)):
            if key.split("#")[0] == name:
                return self.locals[key]
        return None

    def member(self, name):
        for m, typ, _ in self.members:
            if m == name:
                return typ
        return None

    # -- statements

    def stmt(self, s):
        kind, line = s[0], s[1]
        getattr(self, "s_" + kind)(s)

    def s_block(self, s):
        self.scopes.append(set())
        saved = dict(self.locals)
        for x in s[2]:
            self.stmt(x)
        # names leave scope; their slots stay allocated (flat frame)
        gone = self.scopes.pop()
        for key in list(self.locals):
            if key not in saved and key.split("#")[0] in gone:
                slot, typ = self.locals.pop(key)
                self.locals[f"~{key}#{slot}"] = (slot, typ)

    def s_local(self, s):
        _, line, name, typ, init = s
        if init is not None:
            self.value(init)
        slot = self.declare(name, typ, line)
        if init is not None:
            self.store_local(slot, typ)
        else:                       # zero it every time it is reached
            self.emit("push 0")     # (a loop body reuses the slot)
            self.emit(f"storel {slot}")

    def s_expr(self, s):
        e = s[2]
        if e[0] != "call":
            self.err(s[1], "an expression statement must be a call")
        if self.call(e) is not None:
            self.emit("drop              ; unused result")

    def s_assign(self, s):
        _, line, op, lhs, rhs = s
        if lhs[0] == "index":                 # ew[dst] = src
            if op != "=":
                self.err(line, "only = for a whole site")
            self.window(lhs[2], line)
            src = rhs
            if src[0] == "name" and src[2] in ("Empty",):
                self.value(lhs[3])
                self.site_check(lhs[3])
                self.emit("empty")
                return
            if src[0] == "dot" and src[3] == "instanceof" and \
               src[2][0] == "name" and src[2][2] == "Empty":
                self.value(lhs[3])
                self.emit("empty")
                return
            if src[0] == "name" and src[2] == "self":
                self.emit("push 0            ; self")
            elif src[0] == "index":
                self.window(src[2], line)
                self.value(src[3])
            else:
                self.err(line, "a site takes self, ew[i] or Empty")
            self.value(lhs[3])
            self.emit("copy")
            return
        if lhs[0] == "name" and self.find_local(lhs[2]) is not None:
            slot, typ = self.find_local(lhs[2])
            if op == "=":
                self.value(rhs)
            else:
                self.emit(f"loadl {slot}")
                self.value(rhs)
                self.emit("add" if op == "+=" else "sub")
            self.store_local(slot, typ)
            return
        path, typ = self.member_path(lhs, line)
        self.emit("push 0            ; self")
        if op == "=":
            self.value(rhs)
        else:
            self.emit("push 0")
            self.emit(f"getm {path}")
            self.value(rhs)
            self.emit("add" if op == "+=" else "sub")
        if typ[0] == "bool":
            self.to_bool()
        self.emit(f"setm {path}")

    def s_if(self, s):
        _, line, cond, then, other = s
        lelse = self.new_label("else")
        self.cond_false(cond, lelse)
        self.stmt(then)
        if other is None:
            self.label(lelse)
            return
        lend = self.new_label("endif")
        self.emit(f"jmp {lend}")
        self.label(lelse)
        self.stmt(other)
        self.label(lend)

    def s_while(self, s):
        _, line, cond, body = s
        ltop, lend = self.new_label("while"), self.new_label("wend")
        self.label(ltop)
        self.cond_false(cond, lend)
        self.loops.append((lend, ltop))
        self.stmt(body)
        self.loops.pop()
        self.emit(f"jmp {ltop}")
        self.label(lend)

    def s_for(self, s):
        _, line, init, cond, step, body = s
        self.scopes.append(set())
        if init is not None:
            self.stmt(init)
        ltop, lcont, lend = (self.new_label("for"), self.new_label("next"),
                             self.new_label("fend"))
        self.label(ltop)
        if cond is not None:
            self.cond_false(cond, lend)
        self.loops.append((lend, lcont))
        self.stmt(body)
        self.loops.pop()
        self.label(lcont)
        if step is not None:
            self.stmt(step)
        self.emit(f"jmp {ltop}")
        self.label(lend)
        gone = self.scopes.pop()
        for key in list(self.locals):
            if key.split("#")[0] in gone and not key.startswith("~"):
                slot, typ = self.locals.pop(key)
                self.locals[f"~{key}#{slot}"] = (slot, typ)

    def s_break(self, s):
        if not self.loops:
            self.err(s[1], "break outside a loop")
        self.emit(f"jmp {self.loops[-1][0]}")

    def s_continue(self, s):
        if not self.loops:
            self.err(s[1], "continue outside a loop")
        self.emit(f"jmp {self.loops[-1][1]}")

    def s_return(self, s):
        _, line, val = s
        if self.ret == ("void",):
            if val is not None:
                self.err(line, "a Void method returns no value")
            self.emit("halt1             ; return: commit" if self.is_behave
                      else "ret")
            return
        if val is None:
            self.err(line, "return needs a value")
        self.value(val)
        if self.ret[0] == "u" and self.ret[1] < 32:
            self.clamp(self.ret[1])
        elif self.ret[0] == "bool":
            self.to_bool()
        self.emit("ret")

    # -- helpers

    def store_local(self, slot, typ):
        if typ[0] == "u" and typ[1] < 32:
            self.clamp(typ[1])
        elif typ[0] == "bool":
            self.to_bool()
        self.emit(f"storel {slot}")

    def clamp(self, bits):
        """( v -- min(v, 2^bits - 1) )"""
        mx = (1 << bits) - 1
        lok = self.new_label("fits")
        self.emit("dup")
        self.emit(f"push {mx + 1}")
        self.emit("lt")
        self.emit(f"jnz {lok}")
        self.emit("drop")
        self.emit(f"push {mx}          ; saturate to {bits} bits")
        self.label(lok)

    def to_bool(self):
        self.emit("push 0")
        self.emit("eq")
        self.emit("push 0")
        self.emit("eq")

    def window(self, e, line):
        if not (e[0] == "name" and e[2] == "ew"):
            self.err(line, "only ew[...] can be indexed")

    def site_check(self, e):
        if e[0] == "num" and e[2] >= SITES:
            self.err(e[1], f"site {e[2]} is past 40")

    def member_path(self, e, line):
        """self's member access a.b.c -> (bpasm path, scalar type)."""
        names = []
        while e[0] == "dot":
            names.append(e[3])
            e = e[2]
        if e[0] != "name":
            self.err(line, "not a member of self")
        names.append(e[2])
        names.reverse()
        typ = self.member(names[0])
        if typ is None:
            self.err(line, f"{self.name} has no member {names[0]}")
        for n in names[1:]:
            if typ[0] != "quark":
                self.err(line, f"{n}: not inside a quark")
            found = [t for m, t, _ in self.prog.members_of(typ) if m == n]
            if not found:
                self.err(line, f"quark {typ[1]} has no member {n}")
            typ = found[0]
        if typ[0] == "quark":
            self.err(line, "a whole quark is not a value (name a member)")
        return f"{self.name}.{'.'.join(names)}", typ

    # -- expressions

    def value(self, e):
        """Push e's value."""
        kind, line = e[0], e[1]
        if kind == "num":
            self.emit(f"push {e[2]}")
        elif kind == "name":
            name = e[2]
            loc = self.find_local(name)
            if loc is not None:
                self.emit(f"loadl {loc[0]}")
            elif name in self.consts:
                self.emit(f"push {self.consts[name]}  ; {name}")
            else:
                path, _ = self.member_path(e, line)
                self.emit("push 0            ; self")
                self.emit(f"getm {path}")
        elif kind == "dot":
            path, _ = self.member_path(e, line)
            self.emit("push 0            ; self")
            self.emit(f"getm {path}")
        elif kind == "call":
            if self.call(e) is None:
                self.err(line, "a Void method has no value")
        elif kind == "bin" and e[2] in ("+", "-"):
            self.value(e[3])
            self.value(e[4])
            self.emit("add" if e[2] == "+" else "sub")
        elif kind == "bin" and e[2] in ("==", "!=", "<", "<=", ">", ">="):
            self.compare(e)
        elif kind == "is":
            self.is_test(e)
        elif kind in ("bin", "not"):        # && || ! as a value
            lf, lend = self.new_label("f"), self.new_label("v")
            self.cond_false(e, lf)
            self.emit("push 1")
            self.emit(f"jmp {lend}")
            self.label(lf)
            self.emit("push 0")
            self.label(lend)
        elif kind == "index":
            self.err(line, "a whole site is not a value (use ew[i] is T)")
        else:
            self.err(line, f"cannot compute {kind}")

    def is_test(self, e):
        _, line, site, tname = e
        if site[0] != "index":
            self.err(line, "is: ew[i] is TYPE")
        self.window(site[2], line)
        if tname == "Empty":
            num = 0
        elif tname in self.prog.elements:
            num = self.prog.elements[tname][1][3]
        else:
            self.err(line, f"no element {tname}")
        self.value(site[3])
        self.emit("getf type")
        self.emit(f"push {num}           ; {tname}")
        self.emit("eq")

    def compare(self, e):
        """Push 1 or 0 for a comparison."""
        _, line, op, a, b = e
        self.value(a)
        self.value(b)
        if op in (">", "<="):
            self.emit("swap")
        self.emit("eq" if op in ("==", "!=") else "lt")
        if op in ("!=", ">=", "<="):
            self.emit("push 0")
            self.emit("eq")

    def call(self, e):
        """Push a call's result; return its type (None for Void)."""
        _, line, fn, args = e
        if fn[0] == "dot" and fn[2][0] == "name" and fn[2][2] == "random":
            what = fn[3]
            want = {"between": 2, "oneIn": 1}.get(what)
            if want is None:
                self.err(line, f"random has no {what} (between, oneIn)")
            if len(args) != want:
                self.err(line, f"random.{what} takes {want} argument(s)")
            for a in args:
                self.value(a)
            self.emit("between" if what == "between" else "onein")
            return ("u", 32)
        if fn[0] != "name" or fn[2] not in self.methods:
            self.err(line, "unknown method")
        m = self.methods[fn[2]]
        if fn[2] == "behave":
            self.err(line, "behave() cannot be called")
        if len(args) != len(m[4]):
            self.err(line, f"{fn[2]} takes {len(m[4])} argument(s)")
        for a, (pname, ptyp) in zip(args, m[4]):
            self.value(a)
            if ptyp[0] == "u" and ptyp[1] < 32:
                self.clamp(ptyp[1])
            elif ptyp[0] == "bool":
                self.to_bool()
        self.emit(f"call m_{fn[2]}")
        return None if m[3] == ("void",) else m[3]

    def cond_false(self, e, lf):
        """Jump to lf if e is false, else fall through."""
        kind = e[0]
        if kind == "not":
            self.cond_true(e[2], lf)
        elif kind == "bin" and e[2] == "&&":
            self.cond_false(e[3], lf)
            self.cond_false(e[4], lf)
        elif kind == "bin" and e[2] == "||":
            lt = self.new_label("or")
            self.cond_true(e[3], lt)
            self.cond_false(e[4], lf)
            self.label(lt)
        elif kind == "bin" and e[2] in ("==", "!=", "<", "<=", ">", ">="):
            self.cmp_jump(e, lf, False)
        else:
            self.value(e)
            self.emit(f"jz {lf}")

    def cond_true(self, e, lt):
        """Jump to lt if e is true, else fall through."""
        kind = e[0]
        if kind == "not":
            self.cond_false(e[2], lt)
        elif kind == "bin" and e[2] == "||":
            self.cond_true(e[3], lt)
            self.cond_true(e[4], lt)
        elif kind == "bin" and e[2] == "&&":
            lf = self.new_label("and")
            self.cond_false(e[3], lf)
            self.cond_true(e[4], lt)
            self.label(lf)
        elif kind == "bin" and e[2] in ("==", "!=", "<", "<=", ">", ">="):
            self.cmp_jump(e, lt, True)
        else:
            self.value(e)
            self.emit(f"jnz {lt}")

    def cmp_jump(self, e, lab, on_true):
        """Jump to lab when the comparison is on_true."""
        _, line, op, a, b = e
        zero = b[0] == "num" and b[2] == 0
        if zero and op in ("==", "!=", ">", "<="):
            # x == 0 / x <= 0: x is zero; x != 0 / x > 0: x is nonzero
            self.value(a)
            nonzero = op in ("!=", ">")
            self.emit(f"{'jnz' if nonzero == on_true else 'jz'} {lab}")
            return
        self.value(a)
        self.value(b)
        if op in (">", "<="):
            self.emit("swap")
        self.emit("eq" if op in ("==", "!=") else "lt")
        # the pushed flag is the truth of: ==, <, > (after swap), and the
        # NEGATION of: !=, >=, <=
        positive = op in ("==", "<", ">")
        self.emit(f"{'jnz' if positive == on_true else 'jz'} {lab}")


